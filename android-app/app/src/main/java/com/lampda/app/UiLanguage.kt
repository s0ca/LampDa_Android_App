internal fun uiMessage(text: String): Pair<Int, List<String>>? {
    UiResourceIds[text]?.let { return it to emptyList() }
    UiTemplates.forEach { (pattern, resource) ->
        pattern.matchEntire(text)?.let { return resource to it.groupValues.drop(1) }
    }
    return null
}

internal fun translatedUiText(resources: Resources, text: String): String {
    uiMessage(text)?.let { (id, args) -> return resources.getString(id, *args.toTypedArray()) }
    if (text.startsWith("Start ")) return resources.getString(R.string.ui_start_timer,
        translatedUiText(resources, text.removePrefix("Start ")))
    Regex("""^(Sunrise|Sunset) (\d+:\d{2}:\d{2})$""").matchEntire(text)?.let {
        return resources.getString(R.string.ui_timer_remaining,
            translatedUiText(resources, it.groupValues[1]), it.groupValues[2])
    }
    if (" | " in text) return text.split(" | ").joinToString(" | ") { translatedUiText(resources, it.trim()) }
    if (" / " in text) return text.split(" / ").joinToString(" / ") { translatedUiText(resources, it) }
    return text
}

@Composable
internal fun uiString(text: String): String {
    val resources = LocalUiResources.current ?: androidx.compose.ui.platform.LocalContext.current.resources
    return translatedUiText(resources, text)
}

@Composable
internal fun AppText(
    text: String,
    modifier: Modifier = Modifier,
    color: Color = Color.Unspecified,
    fontWeight: FontWeight? = null,
    style: TextStyle = LocalTextStyle.current,
) {
    Text(uiString(text), modifier = modifier, color = color, fontWeight = fontWeight, style = style)
}
